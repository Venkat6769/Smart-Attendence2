/**
 * utils/pdf.js
 * Generates a PDF attendance report for a course using PDFKit.
 * Returns a Buffer that can be sent as an HTTP response with Content-Type: application/pdf.
 */

const PDFDocument = require('pdfkit');

// Color palette matching the UI theme
const COLORS = {
  plum:    '#1e1b2e',
  violet:  '#7c3aed',
  success: '#059669',
  danger:  '#e11d48',
  warning: '#d97706',
  light:   '#f9f8ff',
  gray:    '#6b7280',
};

/**
 * generateAttendancePDF — builds a PDF report for a course's attendance
 * @param {object} course      - { code, title }
 * @param {Array}  rows        - array of formatted attendance rows from formatAttendanceRow()
 * @param {object} summary     - { totalStudents, averagePercentage, flaggedCount }
 * @returns {Promise<Buffer>}  - the PDF as a binary buffer
 */
function generateAttendancePDF(course, rows, summary) {
  return new Promise((resolve, reject) => {
    const doc    = new PDFDocument({ margin: 50, size: 'A4' });
    const chunks = [];

    // Collect PDF data chunks into an array, then combine into a Buffer on finish
    doc.on('data',  chunk => chunks.push(chunk));
    doc.on('end',   ()    => resolve(Buffer.concat(chunks)));
    doc.on('error', err   => reject(err));

    // ── Header ──────────────────────────────────────────────────────────────
    doc.fillColor(COLORS.plum)
       .fontSize(22)
       .font('Helvetica-Bold')
       .text('Smart Attendance System', { align: 'center' });

    doc.fontSize(12)
       .font('Helvetica')
       .fillColor(COLORS.gray)
       .text('University Attendance Report', { align: 'center' });

    doc.moveDown();

    // ── Course Info ──────────────────────────────────────────────────────────
    doc.fillColor(COLORS.violet)
       .fontSize(16)
       .font('Helvetica-Bold')
       .text(`${course.code} — ${course.title}`);

    doc.fillColor(COLORS.gray)
       .fontSize(10)
       .font('Helvetica')
       .text(`Generated: ${new Date().toLocaleDateString('en-GB', {
         day: 'numeric', month: 'long', year: 'numeric'
       })}`);

    doc.moveDown();

    // ── Summary Box ──────────────────────────────────────────────────────────
    doc.fillColor(COLORS.plum)
       .fontSize(12)
       .font('Helvetica-Bold')
       .text('Summary');

    doc.font('Helvetica').fontSize(10).fillColor(COLORS.plum);
    doc.text(`Total Students:       ${summary.totalStudents}`);
    doc.text(`Average Attendance:   ${summary.averagePercentage}%`);
    doc.text(`Students At Risk (<75%): ${summary.flaggedCount}`);

    doc.moveDown();

    // ── Table Header ──────────────────────────────────────────────────────────
    const tableTop  = doc.y;
    const col       = { name: 50, matric: 200, present: 310, total: 360, pct: 410, status: 470 };
    const rowHeight = 20;

    // Draw header row background
    doc.rect(40, tableTop, 520, rowHeight).fill(COLORS.violet);

    doc.fillColor('#ffffff')
       .fontSize(9)
       .font('Helvetica-Bold');

    doc.text('Student Name',  col.name,   tableTop + 5, { width: 140 });
    doc.text('Matric No.',    col.matric, tableTop + 5, { width: 100 });
    doc.text('Present',       col.present,tableTop + 5, { width: 44 });
    doc.text('Total',         col.total,  tableTop + 5, { width: 44 });
    doc.text('Pct %',         col.pct,    tableTop + 5, { width: 50 });
    doc.text('Status',        col.status, tableTop + 5, { width: 60 });

    // ── Table Rows ──────────────────────────────────────────────────────────
    let y = tableTop + rowHeight;

    rows.forEach((row, i) => {
      // Alternate row background for readability
      const bg = i % 2 === 0 ? '#ffffff' : '#f3f0ff';
      doc.rect(40, y, 520, rowHeight).fill(bg);

      const statusColor = row.flagged ? COLORS.danger : COLORS.success;

      doc.fillColor(COLORS.plum).fontSize(9).font('Helvetica');
      doc.text(row.name,          col.name,   y + 5, { width: 140 });
      doc.text(row.matric_number, col.matric, y + 5, { width: 100 });
      doc.text(String(row.present),col.present,y + 5, { width: 44 });
      doc.text(String(row.total), col.total,  y + 5, { width: 44 });
      doc.text(`${row.percentage}%`, col.pct, y + 5, { width: 50 });

      doc.fillColor(statusColor).font('Helvetica-Bold')
         .text(row.status, col.status, y + 5, { width: 60 });

      y += rowHeight;

      // Start a new page if we're near the bottom
      if (y > doc.page.height - 80) {
        doc.addPage();
        y = 50;
      }
    });

    // ── Footer ──────────────────────────────────────────────────────────────
    doc.moveDown(2);
    doc.fillColor(COLORS.gray)
       .fontSize(8)
       .font('Helvetica')
       .text('This report was auto-generated by Smart Attendance System.', { align: 'center' });

    doc.end();
  });
}

module.exports = { generateAttendancePDF };
